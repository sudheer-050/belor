const assert = require('node:assert/strict');
const { detect, launch } = require('../src/resume-tools');
const tool = { id: 'codex', file: "C:\\A folder\\O'Brien\\codex.exe", args: ['untrusted-ignored'] };
const args = launch(tool);
assert(args.includes('-NoExit'), 'return to a usable shell after the application exits');
const command = Buffer.from(args[args.indexOf('-EncodedCommand') + 1], 'base64').toString('utf16le');
assert(command.includes("& 'C:\\A folder\\O''Brien\\codex.exe' 'resume' '--all'"));
assert(command.includes('pwsh-init.ps1'), 'keep Belor shell integration');
assert(!command.includes('untrusted-ignored'));
const claudeArgs = launch({ id: 'claude', file: 'C:\\claude.exe' });
assert(Buffer.from(claudeArgs.at(-1), 'base64').toString('utf16le').includes("& 'C:\\claude.exe' '--resume';"));
assert(command.includes(']133;D;'), 'clear agent state and report the result when the resumed app exits');
const exactId = '01234567-89ab-4cde-8fab-0123456789ab';
const exactCommand = Buffer.from(launch(tool, exactId).at(-1), 'base64').toString('utf16le');
assert(exactCommand.includes(`'resume' '${exactId}'`));
assert(!exactCommand.includes('--all'), 'identified sessions must open directly, without a picker');
assert.throws(() => launch(tool, "id'; unsafe-command"), /session ID/);
assert.throws(() => launch({ id: 'unknown', file: 'C:\\anything.exe' }), /installed application/);
for (const installed of detect()) assert(['codex', 'claude'].includes(installed.id));
console.log('Resume launch checks passed. Installed: ' + detect().map(tool => tool.label).join(', '));
