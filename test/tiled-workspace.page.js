(async () => {
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  for (let i = 0; i < 100 && !window.__st; i++) await pause(100);
  check(window.__st, 'Renderer did not initialize');
  const st = window.__st;
  if (document.body.classList.contains('collapsed')) document.getElementById('collapse-btn').click();
  const visible = () => [...st.tabs.values()].filter(t => t.el.classList.contains('visible'));
  const bounds = () => visible().map(t => t.el.getBoundingClientRect());
  const verify = async count => {
    await pause(250);
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    check(visible().length === count, `Expected ${count} visible panes`);
    const container = document.getElementById('terms').getBoundingClientRect();
    const boxes = bounds();
    boxes.forEach((a, i) => {
      check(a.width > 100 && a.height > 100, `Pane ${i} too small`);
      check(a.left >= container.left && a.right <= container.right && a.top >= container.top && a.bottom <= container.bottom, 'Pane outside workspace');
      boxes.slice(i + 1).forEach(b => check(a.right <= b.left || b.right <= a.left || a.bottom <= b.top || b.bottom <= a.top, 'Panes overlap'));
    });
    for (const t of visible()) {
      const dims = t.fit.proposeDimensions();
      check(t.term.cols === dims.cols && t.term.rows === dims.rows, `Terminal ${t.id} not resized to pane: ${t.term.cols}x${t.term.rows} expected ${dims.cols}x${dims.rows}`);
    }
  };
  st.setLayout('full');
  const initialCount = st.tabs.size;
  st.setLayout('grid'); await verify(1);
  check(st.tabs.size === initialCount, 'Switching view created terminals');
  while (st.tabs.size < 7) await st.openTab('powershell', { activate: false, userTitle: `Terminal ${st.tabs.size + 1}` });
  const ids = [...st.tabs.keys()];
  for (let n = 2; n <= 6; n++) {
    st.selectGridTab(ids[n - 1], true); await verify(n);
    const boxes = bounds();
    if (n <= 3) check(boxes.every(b => Math.abs(b.y - boxes[0].y) < 1), 'Up to three tabs must be side by side');
    if (n === 4) check(new Set(boxes.map(b => Math.round(b.y))).size === 2 && new Set(boxes.map(b => Math.round(b.x))).size === 2, 'Four tabs must form a 2 by 2 grid');
    if (n === 5) check(boxes.filter(b => Math.abs(b.y - boxes[0].y) < 1).length === 3, 'Five tabs need three above and two below');
  }
  st.selectGridTab(ids[6], true); await verify(6);
  check(!visible().some(t => t.id === ids[6]), 'Grid exceeded six selected tabs');
  const positions = bounds().map(b => [b.x, b.y, b.width, b.height]);
  st.activate(ids[2]); await pause(100);
  check(JSON.stringify(positions) === JSON.stringify(bounds().map(b => [b.x, b.y, b.width, b.height])), 'Focus moved panes');
  st.togglePaneZoom(); await verify(1);
  check(document.querySelector('#layout-switch [data-view="full"]').getAttribute('aria-pressed') === 'true', 'Expand must switch to Full view');
  st.setLayout('grid'); await verify(6);
  check(st.tabs.size === 7, 'View switch changed terminal count');
  st.selectGridTab(ids[1], false); await verify(5);
  check(!visible().some(t => t.id === ids[1]), 'Deselected tab stayed visible');
  st.selectGridTab(ids[2], false); await verify(4);
  st.selectGridTab(ids[3], false); await verify(3);
  st.selectGridTab(ids[4], false); await verify(2);
  st.selectGridTab(ids[5], false); await verify(1);
  st.selectGridTab(ids[0], false); await verify(1);
  st.selectGridTab(ids[6], true); await verify(2);
  check(visible().some(t => t.id === ids[6]), 'Chosen hidden tab not displayed');
  check(st.tabs.size === 7, 'Unchecking tabs closed their sessions');
  st.tabs.get(ids[0]).term.write('\r\nBELOR_HISTORY_PRESERVED\r\n');
  await pause(100);
  for (const id of ids.slice(1, 5)) st.selectGridTab(id, true);
  await verify(6);
  const inputTab = st.tabs.get(ids[3]);
  inputTab.el.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }));
  inputTab.term.input("Write-Output 'BELOR_PANE_INPUT_OK'\r", true);
  for (let i = 0; i < 50; i++) {
    const buffer = inputTab.term.buffer.active;
    if (Array.from({ length: buffer.length }, (_, n) => buffer.getLine(n)?.translateToString()).some(line => line?.trim() === 'BELOR_PANE_INPUT_OK')) break;
    await pause(200);
  }
  const text = tab => Array.from({ length: tab.term.buffer.active.length }, (_, n) => tab.term.buffer.active.getLine(n)?.translateToString()).join('\n');
  check(text(inputTab).includes('\nBELOR_PANE_INPUT_OK'), 'Input did not reach pane PTY');
  check(text(st.tabs.get(ids[0])).includes('BELOR_HISTORY_PRESERVED'), 'Lost terminal history');
  st.closeTab(ids[1]); await verify(5);
  check(!visible().some(t => t.id === ids[5]), 'Closing a selected tab added an unselected terminal');
  st.selectGridTab(ids[5], true); await verify(6);
  document.getElementById('choose-tabs').click();
  check(!document.getElementById('grid-tabs').hidden, 'Missing tab chooser');
  check(document.querySelectorAll('#grid-tabs input:checked').length === 6, 'Chooser does not reflect grid selection');
  const choice = document.querySelector(`#grid-tabs input[data-id="${ids[5]}"]`);
  choice.click(); await verify(5);
  document.querySelector(`#grid-tabs input[data-id="${ids[5]}"]`).click(); await verify(6);
  document.getElementById('choose-tabs').click();
  document.getElementById('collapse-btn').click();
  for (let i = 0; i < 30 && Math.abs(document.getElementById('sidebar').getBoundingClientRect().width - 56) > 0.1; i++) await pause(100);
  await verify(6);
  check(Math.abs(document.getElementById('sidebar').getBoundingClientRect().width - 56) < 0.1, 'Sidebar did not become icon rail');
  check(document.getElementById('collapse-btn').getAttribute('aria-expanded') === 'false', 'Incorrect collapse state');
  document.getElementById('new-menu-btn').click();
  const menu = document.getElementById('new-menu');
  check(!menu.hidden && menu.getBoundingClientRect().width > 200, 'Rail shell menu inaccessible');
  document.getElementById('new-menu-btn').click();
  st.setLayout('full'); await verify(1);
  check(st.tabs.size === 6, 'Single view killed hidden tabs');
  st.setLayout('grid'); await verify(6);
  check(document.querySelectorAll('#layout-switch button').length === 2, 'Expected only Full view and Grid view');
  check(document.querySelector('#layout-switch [data-view="grid"]').getAttribute('aria-pressed') === 'true', 'View switch selection missing');
  document.querySelector('#layout-switch [data-view="full"]').click(); await verify(1);
  document.querySelector('#layout-switch [data-view="grid"]').dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true })); await verify(6);
  check(JSON.parse(localStorage.getItem('st-settings')).layout === 'grid', 'View preference not saved');
  const sidebar = document.getElementById('tabs');
  const from = sidebar.querySelector(`[data-id="${ids[6]}"]`);
  const target = sidebar.querySelector(`[data-id="${ids[0]}"]`);
  const transfer = new DataTransfer();
  from.dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: transfer }));
  const rect = target.getBoundingClientRect();
  target.dispatchEvent(new DragEvent('dragover', { bubbles: true, dataTransfer: transfer, clientY: rect.top + 1 }));
  target.dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: transfer }));
  from.dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: transfer }));
  check(sidebar.firstElementChild === from, 'Sidebar drag did not move the tab');
  from.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown', ctrlKey: true, shiftKey: true, bubbles: true }));
  check(sidebar.children[1] === from, 'Keyboard tab movement failed');
  const pane = st.tabs.get(ids[4]), destination = st.tabs.get(ids[0]);
  const paneTransfer = new DataTransfer();
  pane.el.querySelector('.pane-header').dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: paneTransfer }));
  destination.el.dispatchEvent(new DragEvent('dragover', { bubbles: true, dataTransfer: paneTransfer }));
  check(destination.el.classList.contains('pane-drop'), 'Missing pane drop feedback');
  destination.el.dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: paneTransfer }));
  pane.el.querySelector('.pane-header').dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: paneTransfer }));
  await verify(6);
  check(pane.el.getBoundingClientRect().left < destination.el.getBoundingClientRect().left, 'Pane drag did not rearrange terminals');
  check(st.tabs.size === 6, 'Moving tabs changed terminal sessions');
  return 'TILED_WORKSPACE_PASS: two views, explicit tab selection, automatic layouts 1-6, no extra terminals, selection cap, no overlap, sizing, focus, input, history, close, rail, chooser';
})()
